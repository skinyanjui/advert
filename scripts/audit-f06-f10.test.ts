test("F07 account deletion is tombstoned, durable, retryable, and blocks new writes", () => {
  const worker = source("src/lib/account-deletion.ts")
  const session = source("src/lib/board-session.ts")
  const api = source("src/app/api/profile/route.ts")
  const cron = source("src/app/api/cron/expiry-reminders/route.ts")
  const sql = source("database/migrations/20261002_audit_f06_f10_hardening.sql")
  assert.ok(worker.indexOf('rpc("begin_board_account_deletion"') < worker.indexOf('rpc("cleanup_board_account_data"'))
  assert.ok(worker.indexOf('storage.from("listing-photos")') < worker.indexOf("auth.admin.deleteUser"))
  assert.match(worker, /markFailure/)
  assert.match(worker, /runAccountDeletionRetries/)
  assert.match(session, /isAccountDeletionPending\(data\.user\.id\)/)
  assert.match(api, /status: completed \? 200 : 202/)
  assert.match(cron, /runAccountDeletionRetries/)
  assert.match(sql, /for update skip locked/i)
  assert.match(sql, /reject_board_write_for_deleting_account/)
  assert.match(sql, /new writes are blocked/i)
})

