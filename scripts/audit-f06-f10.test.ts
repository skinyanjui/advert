test("F09 published legal versions never expose unfinished placeholders and acceptance fails closed", () => {
  const terms = source("src/app/terms/page.tsx")
  const privacy = source("src/app/privacy/page.tsx")
  const legal = source("src/lib/legal.ts")
  const config = source("src/lib/legal-config.ts")
  const gate = source("src/lib/terms-gate.ts")
  const acceptance = source("src/lib/terms-acceptance.ts")
  for (const document of [terms, privacy]) {
    assert.doesNotMatch(document, /\[PLACEHOLDER|LAWYER TO CONFIRM|DRAFT|pending legal review/i)
  }
  assert.doesNotMatch(legal, /-draft/)
  assert.match(config, /LEGAL_DOCUMENTS_APPROVED/)
  assert.match(config, /LEGAL_OPERATOR_NAME/)
  assert.match(config, /LEGAL_OPERATOR_ADDRESS/)
  assert.match(config, /LEGAL_GOVERNING_LAW/)
  assert.match(config, /LEGAL_VENUE/)
  assert.match(gate, /publicationReady/)
  assert.match(acceptance, /published legal documents are not available for acceptance/)
})

